import { requestJson, type ApiResult } from '../lib/api-client';
import type {
  CreateInvoiceFromOrderInput,
  Invoice,
  InvoicePage,
  InvoiceQuery,
  IssueInvoiceInput,
  OpenInvoice,
  PaymentDetail,
  PaymentPage,
  PaymentQuery,
  RecordPaymentInput,
  ReversePaymentInput,
  UpdateInvoiceDueDateInput,
  VoidInvoiceInput,
} from './catalog-service';

const API_BASE = '/api/v1';

/**
 * The invoicing and payments HTTP client.
 *
 * The invoicing domain is real: invoices, lines, payments, allocations and
 * reversals all live in the service, and every decimal arrives as a decimal
 * STRING (quantities 3 places, unit prices 4 places, totals and balances 2
 * places). No arithmetic happens here - the interface shows what was recorded,
 * and the balances, outstanding and overdue figures are computed by the
 * service from the one shared `invoice_balances` view.
 *
 * Issue, void, record and reverse are exactly-once: the caller generates the
 * idempotency key when the dialog OPENS and sends the same key again on a
 * retry, so a retry after a lost answer cannot post the change twice. The key
 * travels in the `Idempotency-Key` header, never in the body. The draft due
 * date update and every allocation carry the version / balance the caller
 * read; the service refuses a stale one.
 *
 * Creating a draft invoice is NOT idempotent - the contract gives it no key,
 * and a duplicate attempt answers 409 INVOICE_ALREADY_EXISTS, which the
 * create dialog shows inline.
 */

/**
 * Builds a query string from the parameters the caller actually gave: a filter
 * that was not chosen is absent, so the service applies its own default rather
 * than being told "all" by a client that never asked.
 */
function buildQuery(params: Record<string, string | number | boolean | undefined>): string {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === '') continue;
    query.set(key, String(value));
  }
  const queryString = query.toString();
  return queryString ? `?${queryString}` : '';
}

// --- Invoices -----------------------------------------------------------------

/** Creates a draft invoice from a shipped sales order. Not idempotent. */
export async function createInvoiceFromOrder(input: CreateInvoiceFromOrderInput): Promise<ApiResult<Invoice>> {
  return requestJson<Invoice>(`${API_BASE}/sales-orders/${encodeURIComponent(input.orderId)}/invoices`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({}),
  });
}

export async function listInvoices(query: InvoiceQuery): Promise<ApiResult<InvoicePage>> {
  return requestJson<InvoicePage>(
    `${API_BASE}/invoices${buildQuery({
      search: query.search,
      status: query.status,
      overdue: query.overdue,
      orderId: query.orderId,
      page: query.page,
      pageSize: query.pageSize,
      sortBy: query.sortBy,
      sortOrder: query.sortOrder,
    })}`,
    { method: 'GET' },
  );
}

/** The open invoices of one customer: ISSUED or PARTIALLY_PAID with balance > 0. */
export async function listOpenInvoicesForCustomer(customerId: string): Promise<ApiResult<readonly OpenInvoice[]>> {
  return requestJson<readonly OpenInvoice[]>(
    `${API_BASE}/invoices/open${buildQuery({ customerId })}`,
    { method: 'GET' },
  );
}

export async function getInvoice(id: string): Promise<ApiResult<Invoice>> {
  return requestJson<Invoice>(`${API_BASE}/invoices/${encodeURIComponent(id)}`, {
    method: 'GET',
  });
}

/** Updates a draft invoice's due date; the version must match the caller's read. */
export async function updateInvoiceDueDate(input: UpdateInvoiceDueDateInput): Promise<ApiResult<Invoice>> {
  return requestJson<Invoice>(`${API_BASE}/invoices/${encodeURIComponent(input.id)}`, {
    method: 'PUT',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      dueDate: input.dueDate,
      version: input.version,
    }),
  });
}

/**
 * Issues a draft invoice: assigns the INV- number and fixes its dates.
 *
 * The idempotency key is generated by the CALLER (when the dialog opens) and
 * travels in the `Idempotency-Key` header, not in the body: a retry after a
 * lost answer sends the same key and the stored response is replayed, so the
 * number is allocated exactly once.
 */
export async function issueInvoice(input: IssueInvoiceInput): Promise<ApiResult<Invoice>> {
  const { idempotencyKey, id } = input;
  return requestJson<Invoice>(`${API_BASE}/invoices/${encodeURIComponent(id)}/issue`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'Idempotency-Key': idempotencyKey,
    },
    body: JSON.stringify({ dueDate: input.dueDate }),
  });
}

/**
 * Voids a draft invoice, or an issued one with no active allocations.
 *
 * The idempotency key is generated by the CALLER (when the dialog opens) and
 * travels in the `Idempotency-Key` header; the reason travels in the body and
 * is stored with the void in the same transaction.
 */
export async function voidInvoice(input: VoidInvoiceInput): Promise<ApiResult<Invoice>> {
  const { idempotencyKey, id } = input;
  return requestJson<Invoice>(`${API_BASE}/invoices/${encodeURIComponent(id)}/void`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'Idempotency-Key': idempotencyKey,
    },
    body: JSON.stringify({ reason: input.reason }),
  });
}

