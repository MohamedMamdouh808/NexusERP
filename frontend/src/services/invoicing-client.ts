export async function getPayment(id: string): Promise<ApiResult<PaymentDetail>> {
  return requestJson<PaymentDetail>(`${API_BASE}/payments/${encodeURIComponent(id)}`, {
    method: 'GET',
  });
}

/**
 * Records a payment and allocates it across the customer's open invoices.
 *
 * The idempotency key is generated by the CALLER (when the form opens) and
 * travels in the `Idempotency-Key` header. Each allocation carries the balance
 * the form displayed as `expectedBalance`; if the service recomputes a
 * different balance under its lock, the whole payment is refused with 409
 * BALANCE_CHANGED and nothing is written.
 */
export async function recordPayment(input: RecordPaymentInput): Promise<ApiResult<PaymentDetail>> {
  const { idempotencyKey, ...body } = input;
  return requestJson<PaymentDetail>(`${API_BASE}/payments`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'Idempotency-Key': idempotencyKey,
    },
    body: JSON.stringify(body),
  });
}

/**
 * Reverses a recorded payment. The payment row is never changed; a reversal
 * row is the only sign that the payment no longer counts towards balances.
 *
 * The idempotency key is generated by the CALLER (when the dialog opens) and
 * travels in the `Idempotency-Key` header.
 */
export async function reversePayment(input: ReversePaymentInput): Promise<ApiResult<PaymentDetail>> {
  const { idempotencyKey, paymentId } = input;
  return requestJson<PaymentDetail>(`${API_BASE}/payments/${encodeURIComponent(paymentId)}/reverse`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'Idempotency-Key': idempotencyKey,
    },
    body: JSON.stringify({ reason: input.reason }),
  });
}
