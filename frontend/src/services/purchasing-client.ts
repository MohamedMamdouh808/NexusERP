// --- Goods receipts ------------------------------------------------------------

/**
 * Posts a goods receipt.
 *
 * The idempotency key is generated by the CALLER (when the dialog opens) and
 * travels in the `Idempotency-Key` header, not in the body: a retry after a
 * lost answer sends the same key and the stored result is replayed, so the
 * movement, the received quantities and the status change happen exactly once.
 */
export async function receiveGoods(input: ReceiveGoodsInput): Promise<ApiResult<ReceiveGoodsResult>> {
  const { idempotencyKey, orderId, ...body } = input;
  return requestJson<ReceiveGoodsResult>(
    `${API_BASE}/purchase-orders/${encodeURIComponent(orderId)}/receipts`,
    {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'Idempotency-Key': idempotencyKey,
      },
      body: JSON.stringify({ lines: body.lines }),
    },
  );
}

export async function listGoodsReceipts(query: GoodsReceiptQuery): Promise<ApiResult<GoodsReceiptPage>> {
  return requestJson<GoodsReceiptPage>(
    `${API_BASE}/goods-receipts${buildQuery({
      search: query.search,
      startDate: query.startDate,
      endDate: query.endDate,
      page: query.page,
      pageSize: query.pageSize,
      sortBy: query.sortBy,
      sortOrder: query.sortOrder,
    })}`,
    { method: 'GET' },
  );
}
