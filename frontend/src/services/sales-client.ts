import { requestJson, type ApiResult } from '../lib/api-client';
import type {
  CancelSalesOrderInput,
  ConfirmSalesOrderInput,
  CreateSalesOrderInput,
  SalesOrder,
  SalesOrderActionResult,
  SalesOrderPage,
  SalesOrderQuery,
  ShipSalesOrderInput,
  ShipSalesOrderResult,
  Shipment,
  ShipmentPage,
  ShipmentQuery,
  UpdateSalesOrderInput,
} from './catalog-service';

const API_BASE = '/api/v1';

/**
 * The sales HTTP client.
 *
 * The sales domain is real: orders, lines, reservations and shipments all live
 * in the service, and every decimal arrives as a decimal STRING (quantities 3
 * places, unit prices 4 places, totals 2 places). No arithmetic happens here -
 * the interface shows what was recorded.
 *
 * Confirm, cancel and ship are exactly-once: the caller generates the
 * idempotency key when the dialog OPENS and sends the same key again on a retry,
 * so a retry after a lost answer cannot post the movement twice. Order writes
 * carry the version the caller read; the service refuses a stale one.
 */

/**
 * Builds a query string from the parameters the caller actually gave: a filter
 * that was not chosen is absent, so the service applies its own default rather
 * than being told "all" by a client that never asked.
 */
function buildQuery(params: Record<string, string | number | boolean | undefined>): string {
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(params)) {
    if (value === undefined || value === '') continue;
    query.set(key, String(value));
  }
  const queryString = query.toString();
  return queryString ? `?${queryString}` : '';
}

// --- Sales orders -----------------------------------------------------------

export async function listSalesOrders(query: SalesOrderQuery): Promise<ApiResult<SalesOrderPage>> {
  return requestJson<SalesOrderPage>(
    `${API_BASE}/sales-orders${buildQuery({
      search: query.search,
      status: query.status,
      page: query.page,
      pageSize: query.pageSize,
      sortBy: query.sortBy,
      sortOrder: query.sortOrder,
    })}`,
    { method: 'GET' },
  );
}

export async function getSalesOrder(id: string): Promise<ApiResult<SalesOrder>> {
  return requestJson<SalesOrder>(`${API_BASE}/sales-orders/${encodeURIComponent(id)}`, {
    method: 'GET',
  });
}

export async function createSalesOrder(
  input: CreateSalesOrderInput,
): Promise<ApiResult<SalesOrder>> {
  return requestJson<SalesOrder>(`${API_BASE}/sales-orders`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      customerId: input.customerId,
      warehouseId: input.warehouseId,
      orderDate: input.orderDate,
      notes: input.notes,
      lines: input.lines,
    }),
  });
}

export async function updateSalesOrder(
  input: UpdateSalesOrderInput,
): Promise<ApiResult<SalesOrder>> {
  return requestJson<SalesOrder>(`${API_BASE}/sales-orders/${encodeURIComponent(input.id)}`, {
    method: 'PUT',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      customerId: input.customerId,
      warehouseId: input.warehouseId,
      orderDate: input.orderDate,
      notes: input.notes,
      lines: input.lines,
      version: input.version,
    }),
  });
}

export async function confirmSalesOrder(
  input: ConfirmSalesOrderInput,
): Promise<ApiResult<SalesOrderActionResult>> {
  return requestJson<SalesOrderActionResult>(
    `${API_BASE}/sales-orders/${encodeURIComponent(input.orderId)}/confirm`,
    {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'Idempotency-Key': input.idempotencyKey,
      },
      body: JSON.stringify({ version: input.version }),
    },
  );
}

export async function cancelSalesOrder(
  input: CancelSalesOrderInput,
): Promise<ApiResult<SalesOrderActionResult>> {
  return requestJson<SalesOrderActionResult>(
    `${API_BASE}/sales-orders/${encodeURIComponent(input.orderId)}/cancel`,
    {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'Idempotency-Key': input.idempotencyKey,
      },
      body: JSON.stringify({ version: input.version }),
    },
  );
}

// --- Shipments --------------------------------------------------------------

/**
 * Posts a shipment for a confirmed sales order.
 *
 * The idempotency key is generated by the CALLER (when the dialog opens) and
 * travels in the `Idempotency-Key` header, not in the body: a retry after a
 * lost answer sends the same key and the stored result is replayed, so the
 * movement, the consumed reservations and the status change happen exactly
 * once.
 *
 * One shipment ships the whole order: the body carries no quantities - each
 * shipment line ships its full reserved quantity.
 */
export async function shipSalesOrder(
  input: ShipSalesOrderInput,
): Promise<ApiResult<ShipSalesOrderResult>> {
  const { idempotencyKey, orderId } = input;
  return requestJson<ShipSalesOrderResult>(
    `${API_BASE}/sales-orders/${encodeURIComponent(orderId)}/shipments`,
    {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        'Idempotency-Key': idempotencyKey,
      },
      body: JSON.stringify({}),
    },
  );
}

export async function listShipments(query: ShipmentQuery): Promise<ApiResult<ShipmentPage>> {
  return requestJson<ShipmentPage>(
    `${API_BASE}/shipments${buildQuery({
      search: query.search,
      startDate: query.startDate,
      endDate: query.endDate,
      page: query.page,
      pageSize: query.pageSize,
      sortBy: query.sortBy,
      sortOrder: query.sortOrder,
    })}`,
    { method: 'GET' },
  );
}

export async function getShipment(id: string): Promise<ApiResult<Shipment>> {
  return requestJson<Shipment>(`${API_BASE}/shipments/${encodeURIComponent(id)}`, {
    method: 'GET',
  });
}
